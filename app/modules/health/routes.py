"""Health, index, and OpenAPI/Swagger routes."""
from flask import jsonify, render_template, current_app

from app import api
from app.modules.health import bp


@bp.route('/', methods=['GET'])
def index():
    """Root endpoint — used by tests and load balancers."""
    return {'message': 'Hello, World!'}, 200


@bp.route('/health', methods=['GET'])
def health_check():
    """Liveness probe — returns 200 when the app is running."""
    return {'status': 'ok'}, 200


@bp.route('/docs')
def swagger_ui():
    """Render the Swagger UI explorer."""
    return render_template('swagger_ui.html')


@bp.route('/openapi.json')
def openapi_json():
    """Return the OpenAPI spec generated by flask-smorest."""
    spec_dict = api.spec.to_dict()
    spec_dict['openapi'] = current_app.config.get('OPENAPI_VERSION', '3.0.2')
    spec_dict.setdefault('info', {
        'title': current_app.config.get('API_TITLE', 'Flask API'),
        'version': current_app.config.get('API_VERSION', 'v1'),
    })
    spec_dict.setdefault('paths', {})
    return jsonify(spec_dict)